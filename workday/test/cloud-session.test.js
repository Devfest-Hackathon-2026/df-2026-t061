import test from "node:test";
import assert from "node:assert/strict";
import {mkdtemp,mkdir,writeFile,rm} from "node:fs/promises";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {cloudSession,reserveCloudSlot} from "../lib/cloud-session.js";
test("one approval allows only ten attempts while retaining previous usage across tasks and concurrent requests",async t=>{
 const old=process.cwd(),env=process.env.NODE_ENV, dir=await mkdtemp(join(tmpdir(),"cloud-limit-"));
 process.chdir(dir);process.env.NODE_ENV="development";
 t.after(async()=>{process.chdir(old);if(env===undefined)delete process.env.NODE_ENV;else process.env.NODE_ENV=env;await rm(dir,{recursive:true,force:true});});
 const folder=".workday-local/inference";await mkdir(folder,{recursive:true});
 const session={id:"test",company:"架空社",project:"devfest-512005",model:"gemini-3.1-flash-lite",maxCalls:10,issuedAt:Date.now(),expiresAt:Date.now()+60000};
 await writeFile(folder+"/session.json",JSON.stringify(session));
 assert.equal((await cloudSession({company:"別会社"})).remaining,10);
 const ticket=await cloudSession({company:"架空社"});
 await reserveCloudSlot(ticket,{status:"complete"});
 assert.equal((await cloudSession({company:"別会社"})).remaining,9);
 const attempts=await Promise.allSettled(Array.from({length:20},()=>reserveCloudSlot(ticket,{status:"reserved"})));
 assert.equal(attempts.filter(r=>r.status==="fulfilled").length,9);
 assert.equal((await cloudSession({company:"架空社"})).remaining,0);
});
